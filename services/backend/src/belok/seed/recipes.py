def items(recipe: dict) -> list[RecipeItem]:
    out = []
    for n, (name, grams) in enumerate(recipe["items"]):
        kcal, protein, fat, carbs = (v * grams / 100 for v in FOOD[name])
        label = name[0].upper() + name[1:]
        out.append(
            RecipeItem(
                position=n,
                name=label,
                grams=grams,
                kcal=kcal,
                protein=protein,
                fat=fat,
                carbs=carbs,
            )
        )
    return out


async def seed(session: AsyncSession, photos: PhotoStore | None) -> int:
    owner = await session.scalar(select(User).where(User.is_admin.is_(True)).order_by(User.id))
    if owner is None:
        raise SystemExit("no admin user to own the catalog recipes")
    existing = set(await session.scalars(select(Recipe.title).where(Recipe.owner_id == owner.id)))
    added = 0
    for data in RECIPES:
        if data["title"] in existing:
            continue
        photo_key = None
        if photos is not None:
            image = files(__package__).joinpath(f"photos/{data['photo']}.webp").read_bytes()
            photo_key = recipe_key(owner.id)
            await photos.put(photo_key, make_thumbnail(image))
        session.add(
            Recipe(
                owner_id=owner.id,
                title=data["title"],
                portions=data["portions"],
                cooked_grams=data["cooked"],
                steps=[{"text": s, "photo": None} for s in data["steps"]],
                photo_key=photo_key,
                author_name=AUTHOR,
                status=Status.PUBLIC,
                published_at=utcnow(),
                items=items(data),
            )
        )
        added += 1
    await session.commit()
    return added


async def main() -> None:
    logging.basicConfig(level=logging.INFO)
    settings = Settings()
    engine = create_async_engine(settings.database_url)
    try:
        async with async_sessionmaker(engine, expire_on_commit=False)() as session:
            added = await seed(session, PhotoStore.from_settings(settings))
        log.info("added %s recipes", added)
    finally:
        await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
